class Solution {
    public int numIdenticalPairs(int[] nums) {
        int max=0;
        for(int i=0;i<nums.length;i++){
            if(max<nums[i]){
                max=nums[i];
            }
        }

        int[] freq = new int[max+1];

        for (int num : nums) {
            freq[num]++;
        }

        int sum=0;
        int p=0;
         for(int i=0;i<freq.length;i++){
            if(freq[i]!=1){
                p = freq[i]-1;
                sum+=(p*(p+1)/2);
            }
            }
        

         return sum;
    }}
        




































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































    